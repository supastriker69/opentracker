# approvals: agency posts wait; tampering after approval sends a post back; agency editors' data changes
# wait for review; trusted agencies and switching approval off
as_role("owner", reset=True)
seed()
add_person("ngozi", "agency-publisher", "nadmo")
db_until(lambda d: d.get("members/u-agent", {}).get("agency") == "nadmo", "Ngozi is a NADMO publisher")
add_person("ama", "agency-editor", "moi-gh")
db_until(lambda d: d.get("members/u-ed", {}).get("agency") == "moi-gh", "Ama is a MoI agency editor")
posts = lambda d: {k: v for k, v in d.items() if k.startswith("agencyData/u-agent/posts/")}

step("an agency post waits for approval and is hidden from the public")
as_role("agent"); click("[data-act=mode][data-k=agency]")
see("An administrator checks each post.", ".notice.info")
page.select_option("#ag-areas", ["GH-AA"]); fill("#ag-msg", "Odaw overflowing near Kaneshie market."); page.click("#ag-form button[type=submit]")
see("Waiting for approval", "table")
as_role("viewer"); click("#bell"); see("Alerts", "h1"); gone("Odaw overflowing")

step("the owner is told and approves it")
as_role("owner"); click("[data-act=mode][data-k=admin]")
see("Approvals 1", "nav.tabs")
see("1 agency item is waiting for approval")
click("[data-act=ad-tab][data-k=approvals]")
see("Flood warning + phone alert"); see("Odaw overflowing near Kaneshie market.")
click("[data-act=ap-post][data-ok='1']")
db_until(lambda d: any(k.startswith("approvals/") and v["ok"] for k, v in d.items()), "the approval saved")
as_role("viewer"); click("#bell"); see("Odaw overflowing near Kaneshie market.")

step("editing a post after approval takes it off the public pages until it is approved again")
as_role("agent")
pid = list(posts(db()))[0]
eq(page.evaluate("p => claude.use('db').then(d => d.doc(p).update({msg: 'Tampered text'})).then(() => 'ok', e => e.code)", pid), "ok", "agencies may edit their own posts")
as_role("viewer"); click("#bell"); see("Alerts", "h1"); gone("Tampered"); gone("Odaw overflowing")

step("an agency editor's data changes wait for review")
as_role("editor"); click("[data-act=mode][data-k=admin]"); click("[data-act=ad-tab][data-k=hotspots]")
fill("#ad-q", "tetegu"); click("[data-act=ad-edit]"); fill("#f-n", "Tetegu (MoI fix)"); page.click("#ad-form button[type=submit]")
see("Sent to an administrator for approval.", ".toast")
click("[data-act=ad-tab][data-k=safe]"); click("[data-act=ad-ask][data-k=del]"); click("[data-act=ad-yes]")
click("[data-act=ad-tab][data-k=notifications]"); click("[data-act=ad-new][data-k=notifications]")
fill("#f-title", "Curfew lifted"); fill("#f-msg", "Roads in Accra reopened."); page.click("#ad-form button[type=submit]")
d = db_until(lambda d: sum(k.startswith("changes/") and v["status"] == "pending" for k, v in d.items()) == 3, "three changes waiting")
eq(d["hotspots/tetegu"]["n"], "Tetegu", "the flood area is unchanged until approved")
deleted_safe = [v["rid"] for k, v in d.items() if k.startswith("changes/") and v["op"] == "delete"][0]
check(f"safe/{deleted_safe}" in d, "the safe place is still there until approved")
click("[data-act=ad-tab][data-k=overview]")
eq(page.locator("table").first.locator("tr", has_text="Waiting for approval").count(), 3, "the editor sees their three changes waiting")

step("the owner approves two and rejects one with a note")
as_role("owner"); click("[data-act=mode][data-k=admin]"); click("[data-act=ad-tab][data-k=approvals]")
see("Data changes waiting (3)")
see("From Ministry of the Interior (Ghana) (Ama Editor) · Fields: n")
click("[data-act=ap-change][data-ok='1']")
see("Data changes waiting (2)")
fill("input[id^=ap-note]", "Keep this shelter; it is still in use."); click("[data-act=ap-change][data-ok='0']")
see("Data changes waiting (1)")
click("[data-act=ap-change][data-ok='1']")
see("Data changes waiting (0)")
d = db_until(lambda d: d["hotspots/tetegu"]["n"] == "Tetegu (MoI fix)", "the edit applied")
eq(d["hotspots/tetegu"].get("proposedFor"), "moi-gh", "the record notes which agency proposed it")
check(f"safe/{deleted_safe}" in d, "the rejected deletion left the safe place in place")
eq([v["title"] for k, v in d.items() if k.startswith("notifications/")], ["Curfew lifted"], "the approved notification is public")
click("[data-act=ad-tab][data-k=audit]")
for action in ["approved added", "rejected change", "approved edited", "proposed addition", "proposed deletion", "proposed edit"]:
    see(action, "table")
as_role("editor"); click("[data-act=mode][data-k=admin]")
see("Approved", "table"); see("Not approved", "table"); see("Keep this shelter; it is still in use.", "table")

step("a trusted agency's posts go out without approval; approval can be switched off")
as_role("owner"); click("[data-act=mode][data-k=admin]"); click("[data-act=ad-tab][data-k=approvals]")
page.click("details.howto summary"); page.select_option("[data-ap-agency=nadmo]", "auto")
db_until(lambda d: d["config/settings"]["approval"] == {"on": True, "agencies": {"nadmo": "auto"}}, "NADMO trusted")
as_role("viewer"); click("#bell"); see("Tampered text")
as_role("owner"); click("[data-act=mode][data-k=admin]"); click("[data-act=ad-tab][data-k=approvals]"); page.uncheck("#ap-on")
db_until(lambda d: d["config/settings"]["approval"]["on"] is False, "approval switched off")
as_role("editor"); click("[data-act=mode][data-k=admin]"); click("[data-act=ad-tab][data-k=roads]"); click("[data-act=ad-edit]")
fill("#f-n", "Direct edit road"); page.click("#ad-form button[type=submit]")
db_until(lambda d: any(k.startswith("roads/") and v["n"] == "Direct edit road" for k, v in d.items()), "with approval off, the editor's change applies at once")
shot("s6-approvals.png")
