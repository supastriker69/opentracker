# every country: importing live data, the world, a country's flood and heat reach, any town, saved projections
# (made-up test data from webapp/test/fixtures)
FIX = ROOT / "webapp" / "test" / "fixtures"
as_role("owner", reset=True)
seed()

step("import live data: a wrong file is refused, the snapshot is stored per country")
click("[data-act=ad-tab][data-k=live]")
see("Live flood and heat data")
bad = SHOTS / "not-live-data.json"; bad.write_text('{"app":"nope"}')
upload("#hz-import", bad)
see("That isn't an Open Tracker live data file.", "#hz-msg")
upload("#hz-import", FIX / "test-snapshot.json")
see("Imported live data for 3 countries.", ".toast")
d = db_until(lambda d: sorted(k for k in d if k.startswith("hazards/")) == ["hazards/GH", "hazards/IN", "hazards/NG", "hazards/world"], "three countries and the world stored")
see("Now showing data for 3 countries. Updated 28 Oct 2026, 07:00.")
check(any(k.startswith("audit/") and v.get("act") == "imported live data" for k, v in d.items()), "the import is in the audit log")

step("import a saved projection")
click("[data-act=ad-tab][data-k=replays]")
upload("#rp-import", FIX / "test-projection-replay.json")
row = page.locator("table").first.locator("tbody tr", has_text="Projected flood: test valley")
expect(row).to_have_count(1)
eq([c.strip() for c in row.inner_text().split("\t")][1:5], ["Flood model", "9", "Start · 28 October 2026 00:00 GMT", "1.23"], "the projection's row")

step("the world: countries coloured by heat")
click("[data-act=mode][data-k=simple]"); click(".brand")
see("Is my area at risk of flooding or dangerous heat?", "h1")
click("[data-act=world]")
see("Flood and heat around the world", "h1")
see("Countries to watch"); see("Nigeria"); see("2 towns in dangerous heat · 1 current disaster · 1 river rising fast")
map_idle()
eq(page.evaluate("MAPV.map.getLayoutProperty('worldHeat', 'visibility')"), "visible", "the world heat layer is on")
shot("s9-world.png")

step("Nigeria's projected reach, day by day")
click("[data-act=reach][data-k=NG]")
see("Flood and heat reach: Nigeria", "h1")
see("Heatwave or worse in 2 towns where about 4.0 million people live.")
see("0 official warnings · 1 river rising · 0 places with heavy rain · 1 current disaster")
see("Orange flood alert in Nigeria (test)"); see("River near Kano rising fast: flow up to 2.6 times today's within a week")
see("Maiduguri"); see("High 43 °C, feels like 46 °C")
map_idle()
eq(src_count("heatReach"), 2, "two towns' heat reach drawn")
eq(src_count("floodReach"), 2, "the disaster area and the rising river drawn")
click("[data-act=reach-day][data-k='2']")
eq(page.get_attribute("[data-act=reach-day][data-k='2']", "aria-pressed"), "true", "day 3 chosen")
click("[data-act=reach-play]")
see("Pause", "#reach-play")
expect(page.locator("[data-act=reach-day][aria-pressed=true]")).not_to_have_attribute("data-k", "2")
click("[data-act=reach-play]")
see("Play", "#reach-play")
shot("s9-reach-ng.png")

