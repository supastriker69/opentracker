click(".brand"); fill("#q", "mumbai")
see("Maharashtra, India", "#results")
click("#results [data-act=open]")
see("Mumbai", "h1"); see("Maharashtra, India · about 19 million people")
see("Normal heat"); see("Today: high 33 °C, feels like 36 °C, wet-bulb 27 °C.")
eq(page.locator(".week .day, .week > *").count() >= 7, True, "seven days shown")
click("[data-act=toggle][data-k=heat]")
