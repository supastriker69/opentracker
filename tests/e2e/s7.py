# the rainy-season outlook (simple, map, expert) and contributions from the public
as_role("owner", reset=True)
seed()
contribs = lambda d: [i for k, v in d.items() if k.startswith("contributions/") for i in v["items"].values()]

step("outlook: Ghana's areas ranked for next rainy season")
click(".brand"); click("[data-act=outlook]")
see("2027 rainy season outlook", "h1")
see("3 low · 32 medium · 21 high · 4 very high — across 60 known flood areas.")
see("Lower Weija"); see("about 73% chance · reach 5.2 km · all year")
click("[data-act=open-outlook]")
see("Lower Weija", "h1")
see("of flooding in the 2027 rainy season (about 73% chance).")
see("Weija Dam releases water in most rainy seasons")
see("Flooded in 6 of the last 12 years in our records (most recently 2026).")
click("[data-act=to-map]"); map_idle()
eq(src_count("reach"), 60, "one reach circle per known flood area in Ghana's outlook")
shot("s7-outlook-map.png", full=False)
click(".brand"); click("[data-act=outlook]"); click("[data-act=outlook-map][data-k=NG]"); map_idle()
check(src_count("reach") > 0, "Nigeria's outlook map draws reach circles")

step("expert view, next rainy season")
click("[data-act=mode][data-k=expert]"); page.select_option("select[data-ex=horizon]", "year")
see("88 flood areas · next rainy season", "h2 >> nth=1")

step("a member of the public sends a suggestion and a flood report; bad links are refused")
as_role("stranger"); click("[data-act=contribute][data-k=suggestion]")
fill("#c-text", "Please add Hausa and Twi"); page.click("#contrib-form button[type=submit]")
see("Thank you. We've received it."); see("Waiting to be checked")
click(".brand"); fill("#q", "kaneshie"); click("#results [data-act=open]"); click("[data-act=contribute][data-k=report]")
fill("#c-text", "Market flooded for 3 hours"); fill("#c-src", "javascript:alert(1)"); page.click("#contrib-form button[type=submit]")
see("The link must start with http:// or https://", "#c-err")
fill("#c-src", "https://example.org/video"); fill("#c-date", "2026-06-29"); page.select_option("#c-depth", "knee"); page.click("#contrib-form button[type=submit]")
d = db_until(lambda d: len(contribs(d)) == 2, "both contributions stored")
r = [c for c in contribs(d) if c["type"] == "report"][0]
eq({k: r[k] for k in ("text", "place", "date", "depth", "src")}, {"text": "Market flooded for 3 hours", "place": {"type": "hotspot", "id": "kaneshie"}, "date": "2026-06-29", "depth": "knee", "src": "https://example.org/video"}, "the report as stored")
as_role("viewer"); click("[data-act=contribute][data-k=suggestion]"); fill("#c-text", "hi"); page.click("#contrib-form button[type=submit]")
see("Your access to this page can't send contributions.", "#c-err")

step("an administrator reviews: accepts one with a note, turns the report into a past flood")
as_role("owner"); click("[data-act=mode][data-k=admin]"); click("[data-act=ad-tab][data-k=contributions]")
see("New (2)"); see("From Yaw Stranger · flooded 2026-06-29 · water up to the knees")
fill("input[id^=ct-note]", "Thanks, we will look at languages"); click("[data-act=ct-decide][data-ok=accepted]")
see("Accepted (1)")
page.select_option("#ct-filter", "")
click("[data-act=ct-event]")
eq([page.input_value(s) for s in ("#f-t", "#f-date", "#f-ids", "#f-src")], ["Community report: Kaneshie", "2026-06-29", "kaneshie", "https://example.org/video"], "the new past flood is filled in from the report")
page.click("#ad-form button[type=submit]")
db_until(lambda d: any(k.startswith("events/") and v["t"] == "Community report: Kaneshie" for k, v in d.items()), "the past flood saved")
as_role("stranger"); click("[data-act=contribute][data-k=suggestion]"); click("#contrib-form [data-act=contrib-type]")   # back to the list of what they sent
see("What you've sent"); see("Accepted, thank you · Thanks, we will look at languages"); see("Waiting to be checked")

step("outlook settings are checked before saving")
as_role("owner"); click("[data-act=mode][data-k=admin]"); click("[data-act=ad-tab][data-k=model]")
fill("[data-ol=n][data-i='2']", "NIHSA 2027 Annual Flood Outlook"); fill("[data-ol=areas][data-i='2']", "NG-KO, XX-YY"); page.click("#ad-model button[type=submit]")
see('Unknown region or state IDs in "NIHSA 2027 Annual Flood Outlook": XX-YY', "#ad-err")
fill("[data-ol=areas][data-i='2']", "NG-KO, NG-BE"); fill("[data-ol=boost][data-i='2']", "2"); page.select_option("#o-enso", "lanina"); page.click("#ad-model button[type=submit]")
d = db_until(lambda d: d["config/settings"]["outlook"]["enso"] == "lanina", "the outlook settings saved")
lists = d["config/settings"]["outlook"]["lists"]
eq(len(lists), 3, "a third outlook list was added")
eq((lists[2]["n"], lists[2]["areas"], lists[2]["boost"]), ("NIHSA 2027 Annual Flood Outlook", ["NG-KO", "NG-BE"], 2), "the new outlook list")
