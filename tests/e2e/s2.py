# administration: people, editing with validation, delete and undo, roles, model settings, exports
as_role("owner", reset=True)
seed()

step("add people with roles")
add_person("ama", "data-editor")
db_until(lambda d: d.get("members/u-ed", {}).get("role") == "data-editor", "Ama added as data editor")
add_person("ngozi", "agency-publisher", "nadmo")
d = db_until(lambda d: d.get("members/u-agent", {}).get("agency") == "nadmo", "Ngozi added as NADMO publisher")
eq(d["agencies/nadmo"]["publishers"], ["u-agent"], "NADMO lists its publisher")
see("Ama Editor", "table >> nth=-1"); see("Ngozi Agency", "table >> nth=-1")

step("edit a flood area: out-of-range value refused, then saved")
click("[data-act=ad-tab][data-k=hotspots]")
fill("#ad-q", "tetegu")
click("[data-act=ad-edit]")
fill("#f-n", "Tetegu (edited)"); fill("#f-t", "99999")
page.click("#ad-form button[type=submit]")
see("must be between 5 and 1000", "#ad-err")
fill("#f-t", "55"); page.click("#ad-form button[type=submit]")
d = db_until(lambda d: d["hotspots/tetegu"]["n"] == "Tetegu (edited)", "the edit saved")
eq(d["hotspots/tetegu"]["t"], 55, "the new threshold is saved as a number")

step("a new past flood is checked before it is saved")
click("[data-act=ad-tab][data-k=events]"); click("[data-act=ad-new][data-k=events]")
fill("#f-t", "Test flood"); fill("#f-ids", "nope-1"); page.click("#ad-form button[type=submit]")
see("Unknown flood area IDs: nope-1", "#ad-err")
fill("#f-ids", "tetegu"); fill("#f-src", "javascript:alert(1)"); page.click("#ad-form button[type=submit]")
see("The source link must start with http:// or https://", "#ad-err")
fill("#f-src", "https://example.org/x"); page.click("#ad-form button[type=submit]")
test_events = lambda d: [k for k, v in d.items() if k.startswith("events/") and v.get("t") == "Test flood"]
d = db_until(lambda d: len(test_events(d)) == 1, "the past flood saved")

step("delete it, then undo the delete from the audit log")
fill("#ad-q", "Test flood")
click("[data-act=ad-ask][data-k=del]"); click("[data-act=ad-yes]")
db_until(lambda d: not test_events(d), "the past flood deleted")
click("[data-act=ad-tab][data-k=audit]")
see("deleted", "table"); see("Past floods", "table"); see("edited", "table")
click("[data-act=audit-undo]")
db_until(lambda d: len(test_events(d)) == 1, "the delete undone")
click("[data-act=audit-export]")
until("() => (window.__saved || []).some(f => /^opentracker-audit-\\d{4}-\\d\\d-\\d\\d\\.csv$/.test(f.filename) && f.size > 500)", what="the audit log downloaded as CSV")

step("a new role")
click("[data-act=ad-tab][data-k=roles]"); click("[data-act=role-new]")
fill("#r-n", "Regional officer"); page.check("[data-perm='data.edit']"); page.click("#ad-role button[type=submit]")
see("Regional officer", "table")
d = db_until(lambda d: any(k.startswith("roles/") and v.get("n") == "Regional officer" for k, v in d.items()), "the role saved")
eq([v["perms"] for k, v in d.items() if k.startswith("roles/") and v["n"] == "Regional officer"], [["data.edit"]], "the role has exactly the chosen permission")
click("[data-act=role-new]"); fill("#r-n", "regional OFFICER"); page.check("[data-perm='data.edit']"); page.click("#ad-role button[type=submit]")
see("A role with that name already exists.", "#ad-err")

step("model settings are checked; a site notice is shown as text, not HTML")
click("[data-act=ad-tab][data-k=model]"); fill("#m-med", "0.5"); page.click("#ad-model button[type=submit]")
see("Levels must go up: Medium below High below Very high.", "#ad-err")
fill("#m-med", "0.12"); fill("#m-notice", "Test notice <b>x</b>"); page.click("#ad-model button[type=submit]")
see("Test notice <b>x</b>")
eq(page.locator("#app .notice b").filter(has_text="x").count(), 0, "the notice's HTML is not interpreted")
click("[data-act=ad-tab][data-k=overview]"); click("[data-act=ad-export]")
until("() => (window.__saved || []).some(f => /^opentracker-backup-.*\\.json$/.test(f.filename) && f.size > 50000)", what="the backup downloaded")
shot("s2-admin.png", full=False)
