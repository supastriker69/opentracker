# public notifications: an agency editor proposes one, an administrator approves it, followers see it;
# live pop-ups; an agency post with a phone alert after approval
as_role("owner", reset=True)
page.evaluate("localStorage.removeItem('ft-places'); localStorage.removeItem('ft-seen')")
seed()

step("Ama becomes an agency editor for the Ministry of the Interior (Ghana)")
add_person("ama", "agency-editor", "moi-gh")
d = db_until(lambda d: d.get("members/u-ed", {}).get("agency") == "moi-gh", "Ama linked to MoI")
eq(d["members/u-ed"]["role"], "agency-editor", "her role")
eq(d["agencies/moi-gh"]["publishers"], ["u-ed"], "MoI lists her")

step("a viewer follows Kaneshie")
as_role("viewer")
fill("#q", "kaneshie"); click("#results [data-act=open]"); see("Kaneshie", "h1")
click("[data-act=alert-me]")
see("You get alerts for this place · Turn off", "[data-act=alert-me]")
eq(json.loads(page.evaluate("localStorage.getItem('ft-places')")), ["hotspot:kaneshie"], "the followed place is kept on the device only")
check("u-v" not in json.dumps({k: v for k, v in db().items() if not k.startswith(("hotspots/", "events/", "areas/"))}), "nothing about the viewer is written to the shared database")

step("the agency editor writes a notification; it is checked, then sent for approval")
as_role("editor"); modes_are(["Simple", "Expert", "Agency", "Admin"])
click("[data-act=mode][data-k=admin]")
see("Signed in as Agency editor · Ministry of the Interior (Ghana).")
eq(page.inner_text("nav.tabs").split("\n"), ["Overview", "Flood replays", "Live data", "Send notification", "Warnings", "Rain forecasts", "Dams", "Flood areas", "Past floods",
   "Region reports", "Safe places", "Roads", "Data feeds", "Emergency numbers", "Agency posts"], "an agency editor's tabs")
click("[data-act=ad-tab][data-k=notifications]"); click("[data-act=ad-new][data-k=notifications]")
eq(page.locator("#f-agency option").all_inner_texts(), ["Ministry of the Interior (Ghana)"], "they can send only as their own agency")
fill("#f-title", "Evacuate low areas near Odaw"); fill("#f-msg", "Move to higher ground now. Safe place: Kaneshie Sports Complex.")
fill("#f-areas", "GH-AA,NG-LA"); page.click("#ad-form button[type=submit]")
see("These regions or states aren't in the chosen country: NG-LA", "#ad-err")
fill("#f-areas", "GH-AA"); fill("#f-lat", "5.57"); page.click("#ad-form button[type=submit]")
see("For a spot, enter latitude, longitude and radius, or leave all three blank.", "#ad-err")
fill("#f-lat", ""); page.click("#ad-form button[type=submit]")
see("Sent to an administrator for approval.", ".toast")
d = db_until(lambda d: any(k.startswith("changes/") and v["coll"] == "notifications" for k, v in d.items()), "the notification waits for approval")
check(not any(k.startswith("notifications/") for k in d), "nothing is public before approval")
eq(page.evaluate("REPO.setMember('u-x', {role: 'administrator'}).then(() => 'DONE', e => e.message)"), "Your role doesn't allow you to manage people.", "an agency editor cannot manage people")

step("the administrator approves; the follower sees the alert")
as_role("owner"); click("[data-act=mode][data-k=admin]"); click("[data-act=ad-tab][data-k=approvals]")
see("Data changes waiting (1)")
click("[data-act=ap-change][data-ok='1']")
db_until(lambda d: [v["title"] for k, v in d.items() if k.startswith("notifications/")] == ["Evacuate low areas near Odaw"], "the notification is public")
as_role("viewer")
see("1", "#bell")
click("#bell")
see("Alerts", "h1")
see("Evacuate low areas near Odaw"); see("Safe place: Kaneshie Sports Complex.")
see("Ministry of the Interior (Ghana)")
shot("s5-alerts.png")

step("a new warning for a followed place pops up while the page is open")
click(".brand")
page.evaluate("""__inject('notifications/live1', {level: 'warning', title: 'Weija spill', msg: 'Weija Dam spilling from 14:00. Leave the riverbank.', c: 'GH', areas: ['GH-AA'],
  agency: 'gwl', at: new Date().toISOString(), expires: new Date(Date.now() + 864e5).toISOString()})""")
see("Weija spill · Kaneshie", ".livealert")
see("Weija Dam spilling from 14:00. Leave the riverbank.", ".livealert")
see("Ghana Water Ltd (Weija Dam)", ".livealert")
click("[data-act=live-close]")
expect(page.locator(".livealert")).to_have_count(0)

step("an agency post with a phone alert reaches followers only after approval")
as_role("owner"); add_person("ngozi", "agency-publisher", "nadmo")
db_until(lambda d: d.get("members/u-agent", {}).get("agency") == "nadmo", "Ngozi is a NADMO publisher")
as_role("agent"); click("[data-act=mode][data-k=agency]")
page.select_option("#ag-areas", ["GH-AA"]); fill("#ag-msg", "NADMO: drains overflowing at Kaneshie market.")
page.click("#ag-form button[type=submit]")
see("Waiting for approval", "table")
as_role("viewer"); click("#bell"); see("Alerts", "h1"); gone("drains overflowing")
as_role("owner"); click("[data-act=mode][data-k=admin]"); click("[data-act=ad-tab][data-k=approvals]")
click("[data-act=ap-post][data-ok='1']")
d = db_until(lambda d: any(k.startswith("approvals/") and v["uid"] == "u-agent" and v["ok"] for k, v in d.items()), "the post approved")
check(all(v.get("fp") for k, v in d.items() if k.startswith("approvals/")), "the approval keeps a fingerprint of exactly what was approved")
as_role("viewer"); click("#bell"); see("drains overflowing at Kaneshie market")
page.set_viewport_size({"width": 390, "height": 844})
until("() => document.documentElement.scrollWidth <= 390", what="no sideways scrolling on a phone")
shot("s5-alerts-phone.png", full=False)
