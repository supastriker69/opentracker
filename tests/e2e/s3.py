# agencies: publishing for review, permission checks, the public view, access requests, the editor role
as_role("owner", reset=True)
seed()
add_person("ngozi", "agency-publisher", "nadmo")
db_until(lambda d: d.get("members/u-agent", {}).get("agency") == "nadmo", "Ngozi is a NADMO publisher")
add_person("ama", "data-editor")
d = db_until(lambda d: d.get("members/u-ed", {}).get("role") == "data-editor", "Ama is a data editor")
eq(d["members/u-ed"]["agency"], None, "a data editor acts for no agency, even when an agency was chosen in the form before")
eq(d["agencies/nadmo"]["publishers"], ["u-agent"], "and does not become an agency publisher")

step("an agency publisher posts a warning, a dam status and a reading; each waits for review")
as_role("agent")
modes_are(["Simple", "Expert", "Agency"])
click("[data-act=mode][data-k=agency]")
see("Publishing for National Disaster Management Organisation (NADMO)")
page.select_option("#ag-areas", ["GH-AA"]); fill("#ag-msg", "Heavy rain: move away from the Odaw drains tonight.")
page.click("#ag-form button[type=submit]")
see("Heavy rain: move away from the Odaw drains tonight.", "table")
click("[data-act=ag-type][data-k=dam]"); page.select_option("#ag-dam", "weija"); page.select_option("#ag-status", "release"); fill("#ag-notice", "Spilling from 10:00")
page.click("#ag-form button[type=submit]")
see("Weija Dam: Releasing water · Spilling from 10:00", "table")
click("[data-act=ag-type][data-k=reading]"); fill("#ag-station", "Odaw at Kaneshie"); fill("#ag-value", "2.4"); fill("#ag-lat", "5.57"); fill("#ag-lon", "-0.23")
page.click("#ag-form button[type=submit]")
see("Odaw at Kaneshie: 2.4 m", "table")
eq(page.locator("table tr", has_text="Waiting for approval").count(), 3, "all three posts wait for approval")
eq(len([k for k in db() if k.startswith("agencyData/u-agent/posts/")]), 3, "three posts stored under the agent's own space")

step("the publisher cannot write official data directly")
eq(page.evaluate("claude.use('db').then(d => d.doc('hotspots/tetegu').set({n: 'hack'})).then(() => 'WROTE', e => e.code)"), "invalid_argument", "a direct write to official data is refused")
eq(db()["hotspots/tetegu"]["n"], "Tetegu", "official data unchanged")

step("the public does not see posts that are waiting for approval")
as_role("viewer")
modes_are(["Simple", "Expert", "Agency"])
click("[data-act=country][data-id=GH]"); click("[data-act=open][data-type=area]")
see("Greater Accra Region", "h1")
gone("Odaw drains"); gone("Odaw at Kaneshie")
click("[data-act=mode][data-k=expert]")
see("Use official setting (Typical for the season)", "select[data-dam]")

step("a stranger asks to publish for LASEMA; the owner approves")
as_role("stranger"); click("[data-act=mode][data-k=agency]")
page.select_option("#ag-req-agency", "lasema"); fill("#ag-req-note", "Duty officer, Alausa"); page.click("#ag-request button[type=submit]")
see("Request sent"); see("Lagos State Emergency Management Agency")
as_role("owner"); click("[data-act=mode][data-k=admin]"); click("[data-act=ad-tab][data-k=requests]")
see("Yaw Stranger", "table"); see("Duty officer, Alausa", "table")
click("[data-act=rq-yes]")
d = db_until(lambda d: d["agencies/lasema"]["publishers"] == ["u-x"], "the stranger is now a LASEMA publisher")
eq(d["agencyData/u-x"]["decision"]["approved"], True, "the decision is recorded for the requester")
click("[data-act=ad-tab][data-k=posts]")
see("Heavy rain: move away from the Odaw drains tonight.", "table")
click("[data-act=post-withdraw]")
d = db_until(lambda d: sum(bool(v.get("retracted")) for k, v in d.items() if k.startswith("agencyData/u-agent/posts/")) == 1, "one post withdrawn")
eq([v["retractedBy"] for k, v in d.items() if k.startswith("agencyData/u-agent/posts/") and v.get("retracted")], ["u-owner"], "the withdrawal records who did it")

step("a data editor sees data tabs only and cannot manage people")
as_role("editor"); modes_are(["Simple", "Expert", "Agency", "Admin"])
click("[data-act=mode][data-k=admin]")
tabs = page.inner_text("nav.tabs").split("\n")
check("Flood areas" in tabs and "Past floods" in tabs, "data tabs are shown")
check(not any(t in tabs for t in ["People", "Roles", "Audit log", "Approvals"]), f"people, roles, audit and approvals are hidden: {tabs}")
eq(page.evaluate("REPO.removeMember('u-agent').then(() => 'DONE', e => e.message)"), "Your role doesn't allow you to remove people.", "removing a person is refused")
check("members/u-agent" in db(), "the person is still there")

step("the stranger now publishes for LASEMA")
as_role("stranger"); click("[data-act=mode][data-k=agency]")
see("Publishing for Lagos State Emergency Management Agency (LASEMA)")
