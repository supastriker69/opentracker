# the first visit: an owner on an empty database, the simple flow, and setting up the database
step("owner on an empty database")
as_role("owner", reset=True)
modes_are(["Simple", "Expert", "Agency", "Admin"])
see("Is my area at risk of flooding or dangerous heat?", "h1")

step("simple flow: Ghana, its regions by risk, Greater Accra")
click("[data-act=country][data-id=GH]")
see("Choose a region in Ghana")
see("Greater Accra")
see("24 known flood areas")
eq(page.locator(".list .pick").count(), 16, "Ghana's 16 regions are listed")
click("[data-act=open][data-type=area]")
see("Greater Accra Region", "h1")
see("across 24 known flood areas, next 3 days")
see("Tetegu")
shot("s1-answer.png")
click("[data-act=to-map]")
see("Map", "h1")
map_idle()
check(src_count("hot") > 0, "flood areas are drawn on the map")
shot("s1-map.png", full=False)

step("set up the database from the built-in data")
seed()
d = db()
check(len(d) >= 190, f"the database holds the built-in data ({len(d)} documents)")
eq(sum(k.startswith("hotspots/") for k in d), 88, "88 flood areas")
see("Public pages show the shared database")
