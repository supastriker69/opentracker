# flood replays: import, validation, adding an outline, the model and satellite players, the years slider, deleting
# (the fixtures are made-up test data)
FIX = ROOT / "webapp" / "test" / "fixtures"
as_role("owner", reset=True)
seed()
geo_docs = lambda d: [k for k in d if k.startswith("geo/")]
def cells(name):
    """the cells of the replay table's row for this replay"""
    row = page.locator("table").first.locator("tbody tr", has_text=name)
    expect(row).to_have_count(1)
    return [c.strip() for c in row.inner_text().split("\t")][:5]

step("import a model replay and a satellite replay")
click("[data-act=ad-tab][data-k=replays]")
upload("#rp-import", FIX / "test-terrain-replay.json")
see("Test terrain: Test storm: 120 mm in 3 hours", "table")
upload("#rp-import", FIX / "test-satellite-replay.json")
see("Test outlines (not a real flood)", "table")
rows = page.locator("table").first.locator("tbody tr")
eq(rows.count(), 2, "two replays listed")
eq(cells("Test terrain")[1:], ["Flood model", "16", "Start · 29 June 2026 06:00 GMT", "0.4"], "the model replay's row")
eq(cells("Test outlines")[1:], ["Satellite map", "3", "11 September 2024", "31.47"], "the satellite replay's row")
eq(len(geo_docs(db())), 19, "each step's map layer is stored separately (16 + 3)")

step("a file that is not a replay is refused")
bad = SHOTS / "not-a-replay.json"; bad.write_text('{"app":"x"}')
upload("#rp-import", bad)
see("That isn't an Open Tracker replay file.", ".toast")
eq(rows.count(), 2, "nothing was added")

step("add one dated outline to the satellite replay")
gj = SHOTS / "one-outline.geojson"
gj.write_text(json.dumps({"type": "Feature", "properties": {}, "geometry": {"type": "Polygon", "coordinates": [[[13.12, 11.82], [13.18, 11.82], [13.18, 11.88], [13.12, 11.88], [13.12, 11.82]]]}}))
upload("#ro-file", gj); fill("#ro-date", "2024-09-29"); page.select_option("#ro-target", "test-outlines")
page.click("#ro-form button[type=submit]")
expect(page.locator("table").first.locator("tbody tr", has_text="Test outlines")).to_contain_text("43.37")
eq(cells("Test outlines")[1:], ["Satellite map", "4", "11 September 2024", "43.37"], "the satellite replay now has four dates")

step("watch the model replay hour by hour")
click(".brand"); click("[data-act=replays]")
see("Watch floods over time", "h1")
see("Satellite map · 11 September 2024 · 4 satellite maps · up to 43.37 km² under water")
click("[data-act=replay-open][data-id=test-test]")
see("Start · 29 June 2026 06:00 GMT · 0 km² under water", "#rp-now")
page.fill("#rp-slider", "3"); page.dispatch_event("#rp-slider", "input")
see("3 hours · 29 June 2026 09:00 GMT · 0.4 km² under water", "#rp-now")
map_idle()
eq(src_count("replay"), 3, "hour 3 draws three depth classes")
click("#rp-play")
see("Pause", "#rp-play")
expect(page.locator("#rp-now")).not_to_contain_text("3 hours ·")
click("#rp-play")
see("Play", "#rp-play")
shot("s8-replay-model.png")

step("watch the satellite replay date by date")
click("[data-act=replay-close]"); click("[data-act=replay-open][data-id=test-outlines]")
see("11 September 2024 · 9.96 km² under water", "#rp-now")
eq(page.get_attribute("#rp-slider", "max"), "3", "four dates")
page.fill("#rp-slider", "1"); page.dispatch_event("#rp-slider", "input")
see("17 September 2024 · 31.47 km² under water", "#rp-now")
shot("s8-replay-satellite.png")

step("recorded floods, year by year")
click("[data-act=replay-close]"); click("[data-act=years-map]")
see("2026", ".player-year")
last = int(page.get_attribute("#year-slider", "max"))
eq(last + 1, 25, "25 years, 2002 to 2026")
page.evaluate("v => { const s = document.querySelector('#year-slider'); s.value = v; s.dispatchEvent(new Event('change', {bubbles: true})); }", last - 2)
see("2024", ".player-year")
see("Satellite maps from 2024: Test outlines (not a real flood)", ".card.player")
map_idle()
eq(src_count("replay"), 1, "2024's largest satellite outline is drawn")
click("[data-act=years-play]")
see("2026", ".player-year")
click("[data-act=years-play]")
shot("s8-years.png", full=False)

step("a place's page links to replays there; the public can watch")
click(".brand"); fill("#q", "borno"); click("#results [data-act=open]")
see("Watch floods here over time")
as_role("viewer"); click("[data-act=replays]"); click("[data-act=replay-open]")
see("11 September 2024 · 9.96 km² under water", "#rp-now")

step("deleting a replay removes its map layers too")
as_role("owner"); click("[data-act=mode][data-k=admin]"); click("[data-act=ad-tab][data-k=replays]")
click("[data-act=ad-ask][data-k=rm-replay]"); click("[data-act=ad-yes]")
see("Replay deleted.", ".toast")
d = db_until(lambda d: sum(k.startswith("replays/") for k in d) == 1, "one replay left")
eq(len(geo_docs(d)), 4, "only the remaining replay's four layers are left")
